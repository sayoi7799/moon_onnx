def fnv1a(data: bytes) -> int:
    h = 0x811C9DC5
    for b in data:
        h ^= b
        h = (h * 0x01000193) & 0xFFFFFFFF
    return h


def sha256_file(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def mbt_string(s: str) -> str:
    """Escape a Python str as a MoonBit string literal."""
    out = ['"']
    for ch in s:
        o = ord(ch)
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        elif o < 0x20 or o == 0x7F:
            out.append("\\u{%x}" % o)
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def mbt_base64(data: bytes, indent: str = "  ") -> str:
    """A MoonBit multi-line string literal (#| lines) holding base64 data.

    Lines are 76 characters; the MoonBit side decodes with
    `ignore_whitespace=true`.
    """
    b64 = base64.b64encode(data).decode("ascii")
    lines = [b64[i : i + 76] for i in range(0, len(b64), 76)] or [""]
    body = "\n".join(f"{indent}  #|{line}" for line in lines)
    return f"(\n{body}\n{indent})"


def f32_bits(x: float) -> int:
    return struct.unpack("<I", struct.pack("<f", x))[0]


HEADER = (
    "// Code generated by {script}; DO NOT EDIT.\n"
    "// Source data: {source}\n"
    "// Regenerate: {command}\n\n"
)


def write_generated(path: str, script: str, source: str, command: str, body: str):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER.format(script=script, source=source, command=command))
        f.write(body)
    print("wrote", os.path.relpath(path, ROOT), f"({os.path.getsize(path)} bytes)")
