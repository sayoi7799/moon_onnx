"""Shared helpers for the test-data generators.

All expected values used by the MoonBit tests come from the official `onnx`
Python package (decoding / reference data) and from `onnxruntime` (model
outputs). Versions are pinned in scripts/requirements.txt.
"""

import base64
import hashlib
import os
import struct

